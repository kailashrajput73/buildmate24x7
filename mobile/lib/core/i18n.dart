class LangNotifier extends StateNotifier<String> {
  LangNotifier(String initial) : super(initial);
  Future<void> set(String lang) async {
    state = lang;
    final p = await SharedPreferences.getInstance();
    await p.setString('lang', lang);
  }
}

/// Overridden in main() with the saved language.
final langProvider = StateNotifierProvider<LangNotifier, String>((ref) => LangNotifier('en'));

class Tr {
  final String lang;
  const Tr(this.lang);
  String call(String key) => _strings[lang]?[key] ?? _strings['en']![key] ?? key;
}

final trProvider = Provider<Tr>((ref) => Tr(ref.watch(langProvider)));
