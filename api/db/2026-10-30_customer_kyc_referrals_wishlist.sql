-- =====================================================================================================
-- BuildMate — Customer KYC & reward points, Refer & Earn codes, account wishlist          2026-10-30
--
-- For databases created BEFORE this change (the API creates the schema with EnsureCreated, so new tables and
-- columns are NOT added automatically). Fresh databases get all of this from the code; don't run it there.
--
-- RUN BY HAND, after a backup, on staging first:
--     pg_dump -Fc -d buildmate -f buildmate_before_2026-10-30.dump
--     psql -d buildmate -v ON_ERROR_STOP=1 -f 2026-10-30_customer_kyc_referrals_wishlist.sql
--
-- What it changes (additive only — no data is deleted or rewritten)
--   * users:            + referral_code (unique when set), + referred_by_id (who invited them)
--   * customer_profiles: NEW — KYC status and reward balance for retail customers (one row per customer)
--   * kyc_documents:    partner_profile_id becomes optional; + customer_profile_id (a document belongs to one of them)
--   * wishlist_items:   NEW — products saved by signed-in users (website + app)
--   * Existing partners, orders, rewards and KYC documents are untouched.
--   * Safe to re-run: IF NOT EXISTS everywhere.
--
-- Rollback (only before customers have used the new features):
--     DROP TABLE wishlist_items;
--     ALTER TABLE kyc_documents DROP COLUMN customer_profile_id;  -- then, if no customer documents exist:
--     ALTER TABLE kyc_documents ALTER COLUMN partner_profile_id SET NOT NULL;
--     DROP TABLE customer_profiles;
--     ALTER TABLE users DROP COLUMN referred_by_id, DROP COLUMN referral_code;
-- =====================================================================================================

BEGIN;

-- Refer & Earn ---------------------------------------------------------------------------------------
ALTER TABLE users ADD COLUMN IF NOT EXISTS referral_code  character varying(12) NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS referred_by_id bigint NULL;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_users_users_referred_by_id') THEN
    ALTER TABLE users ADD CONSTRAINT fk_users_users_referred_by_id
      FOREIGN KEY (referred_by_id) REFERENCES users (id) ON DELETE SET NULL;
  END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS ix_users_referral_code  ON users (referral_code) WHERE referral_code IS NOT NULL;
CREATE INDEX        IF NOT EXISTS ix_users_referred_by_id ON users (referred_by_id);

-- Customer KYC + reward points -----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS customer_profiles (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            bigint                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    gstin              character varying(15)    NULL,
    kyc_status         integer                  NOT NULL DEFAULT 0,
    kyc_submitted_at   timestamp with time zone NULL,
    kyc_reviewed_by_id bigint                   NULL REFERENCES users (id) ON DELETE SET NULL,
    kyc_reviewed_at    timestamp with time zone NULL,
    kyc_remarks        text                     NULL,
    reward_balance     numeric(14,2)            NOT NULL DEFAULT 0,
    created_at         timestamp with time zone NOT NULL,
    updated_at         timestamp with time zone NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_customer_profiles_user_id            ON customer_profiles (user_id);
CREATE INDEX        IF NOT EXISTS ix_customer_profiles_kyc_status         ON customer_profiles (kyc_status);
CREATE INDEX        IF NOT EXISTS ix_customer_profiles_kyc_reviewed_by_id ON customer_profiles (kyc_reviewed_by_id);

ALTER TABLE kyc_documents ALTER COLUMN partner_profile_id DROP NOT NULL;
ALTER TABLE kyc_documents ADD COLUMN IF NOT EXISTS customer_profile_id bigint NULL;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_kyc_documents_customer_profiles_customer_profile_id') THEN
    ALTER TABLE kyc_documents ADD CONSTRAINT fk_kyc_documents_customer_profiles_customer_profile_id
      FOREIGN KEY (customer_profile_id) REFERENCES customer_profiles (id) ON DELETE CASCADE;
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS ix_kyc_documents_customer_profile_id ON kyc_documents (customer_profile_id);

-- Account wishlist -----------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS wishlist_items (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id  bigint                   NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    created_at  timestamp with time zone NOT NULL,
    updated_at  timestamp with time zone NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_wishlist_items_user_id_product_id ON wishlist_items (user_id, product_id);
CREATE INDEX        IF NOT EXISTS ix_wishlist_items_product_id         ON wishlist_items (product_id);

COMMIT;

\echo 'Check (expect: customer_profiles 0, wishlist_items 0, referral codes 0, kyc_documents unchanged):'
SELECT count(*) AS customer_profiles FROM customer_profiles;
SELECT count(*) AS wishlist_items    FROM wishlist_items;
SELECT count(*) AS referral_codes    FROM users WHERE referral_code IS NOT NULL;
SELECT count(*) AS kyc_documents     FROM kyc_documents;
