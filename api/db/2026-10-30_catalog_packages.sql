-- Additive upgrade for existing EnsureCreated databases. Run only against an approved target after backup.
-- New databases use the EF model. No products, orders, users, stock or payments are removed.
BEGIN;
SELECT pg_advisory_xact_lock(24071001);
CREATE TABLE IF NOT EXISTS product_types (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_id bigint NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
 name varchar(120) NOT NULL, key varchar(120) NOT NULL,
 is_active boolean NOT NULL DEFAULT true, sort_order integer NOT NULL DEFAULT 0,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 created_by_id bigint NULL, updated_by_id bigint NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_product_types_category_id_key ON product_types(category_id,key);
CREATE TABLE IF NOT EXISTS product_type_sub_categories (
 product_type_id bigint NOT NULL REFERENCES product_types(id) ON DELETE CASCADE,
 sub_category_id bigint NOT NULL REFERENCES sub_categories(id) ON DELETE RESTRICT,
 PRIMARY KEY(product_type_id,sub_category_id)
);
CREATE INDEX IF NOT EXISTS ix_product_type_sub_categories_sub_category_id ON product_type_sub_categories(sub_category_id);
CREATE TABLE IF NOT EXISTS catalog_families (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_id bigint NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
 brand_id bigint NOT NULL REFERENCES brands(id) ON DELETE RESTRICT,
 key varchar(200) NOT NULL, name varchar(200) NOT NULL, image_url varchar(2048) NULL,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 created_by_id bigint NULL, updated_by_id bigint NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_catalog_families_category_id_brand_id_key ON catalog_families(category_id,brand_id,key);
CREATE INDEX IF NOT EXISTS ix_catalog_families_brand_id ON catalog_families(brand_id);
ALTER TABLE products
 ADD COLUMN IF NOT EXISTS product_type_id bigint NULL REFERENCES product_types(id) ON DELETE RESTRICT,
 ADD COLUMN IF NOT EXISTS catalog_family_id bigint NULL REFERENCES catalog_families(id) ON DELETE RESTRICT,
 ADD COLUMN IF NOT EXISTS product_class varchar(120) NULL,
 ADD COLUMN IF NOT EXISTS size varchar(120) NULL,
 ADD COLUMN IF NOT EXISTS size_value numeric(20,6) NULL,
 ADD COLUMN IF NOT EXISTS size_unit varchar(40) NULL,
 ADD COLUMN IF NOT EXISTS size_dimension varchar(20) NULL,
 ADD COLUMN IF NOT EXISTS size_normalized numeric(24,6) NULL,
 ADD COLUMN IF NOT EXISTS length varchar(120) NULL,
 ADD COLUMN IF NOT EXISTS length_value numeric(20,6) NULL,
 ADD COLUMN IF NOT EXISTS length_unit varchar(40) NULL,
 ADD COLUMN IF NOT EXISTS length_normalized numeric(24,6) NULL,
 ADD COLUMN IF NOT EXISTS pack_size numeric(14,3) NULL,
 ADD COLUMN IF NOT EXISTS pack_mrp numeric(14,2) NULL,
 ADD COLUMN IF NOT EXISTS box_discount_type varchar(20) NOT NULL DEFAULT 'None',
 ADD COLUMN IF NOT EXISTS box_discount_value numeric(14,2) NOT NULL DEFAULT 0;
CREATE INDEX IF NOT EXISTS ix_products_product_type_id ON products(product_type_id);
CREATE INDEX IF NOT EXISTS ix_products_catalog_family_id_sequence ON products(catalog_family_id,sequence);
CREATE INDEX IF NOT EXISTS ix_products_category_id_product_type_id_sub_category_id_brand_id ON products(category_id,product_type_id,sub_category_id,brand_id);
CREATE INDEX IF NOT EXISTS ix_products_product_class ON products(product_class);
ALTER TABLE cart_items ADD COLUMN IF NOT EXISTS purchase_unit varchar(10) NOT NULL DEFAULT 'Piece';
DROP INDEX IF EXISTS ix_cart_items_user_id_product_id;
CREATE UNIQUE INDEX IF NOT EXISTS ix_cart_items_user_id_product_id_purchase_unit ON cart_items(user_id,product_id,purchase_unit);
ALTER TABLE order_items
 ADD COLUMN IF NOT EXISTS purchase_unit varchar(10) NOT NULL DEFAULT 'Piece',
 ADD COLUMN IF NOT EXISTS pack_size_snapshot numeric(14,3) NULL,
 ADD COLUMN IF NOT EXISTS pack_mrp_snapshot numeric(14,2) NULL,
 ADD COLUMN IF NOT EXISTS box_price_snapshot numeric(14,2) NULL,
 ADD COLUMN IF NOT EXISTS base_unit_snapshot varchar(40) NULL;
ALTER TABLE quotation_items
 ADD COLUMN IF NOT EXISTS purchase_unit varchar(10) NOT NULL DEFAULT 'Piece',
 ADD COLUMN IF NOT EXISTS pack_size_snapshot numeric(14,3) NULL,
 ADD COLUMN IF NOT EXISTS pack_mrp_snapshot numeric(14,2) NULL,
 ADD COLUMN IF NOT EXISTS box_price_snapshot numeric(14,2) NULL,
 ADD COLUMN IF NOT EXISTS base_unit_snapshot varchar(40) NULL;
-- Only explicit old family assignments are migrated. Never derive identity from a product's name.
INSERT INTO catalog_families(category_id,brand_id,key,name)
 SELECT category_id,brand_id,upper(trim(variant_family)),min(trim(variant_family))
 FROM products WHERE catalog_family_id IS NULL AND nullif(trim(variant_family),'') IS NOT NULL
 GROUP BY category_id,brand_id,upper(trim(variant_family))
 ON CONFLICT(category_id,brand_id,key) DO NOTHING;
UPDATE products p SET catalog_family_id=f.id FROM catalog_families f
 WHERE p.catalog_family_id IS NULL AND f.category_id=p.category_id AND f.brand_id=p.brand_id AND f.key=upper(trim(p.variant_family));
-- Missing Type/Class/Size/Length stay NULL pending explicit mapping or a reviewed Excel import.
-- Existing commercial prices, stock, order quantities and historical totals are untouched.
COMMIT;
