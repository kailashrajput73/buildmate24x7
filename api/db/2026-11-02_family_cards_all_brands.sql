-- =====================================================================================================
-- BuildMate — one listing card per family for all brands ("CPVC PIPE"), card photos, Class label   2026-11-02
--
-- For databases created BEFORE this change (EnsureCreated does not add new tables/columns to an existing database).
-- Needs 2026-10-30_catalog_packages.sql first. Fresh databases get all of this from the code; don't run it there.
--
-- RUN BY HAND, after a backup, on staging first:
--     pg_dump -Fc -d buildmate -f buildmate_before_2026-11-02.dump
--     psql -d buildmate -v ON_ERROR_STOP=1 -f 2026-11-02_family_cards_all_brands.sql
--
-- What it changes (additive only — no data is deleted or rewritten)
--   * product_types:        + group_across_brands (NULL = automatic: Pipe & Fitting types and Electrical › Cable)
--                           + class_label         (NULL = automatic: "Color" for Electrical › Cable, else "Class")
--   * catalog_family_cards: NEW — card photo of a family shown once for all brands (set in Dashboard › Types & families)
--   * Products, brand families, prices, stock, orders and customers are untouched. Safe to re-run.
--
-- Rollback (only before any card photo has been set):  psql -f 2026-11-02_family_cards_all_brands_rollback.sql
-- =====================================================================================================
BEGIN;
SELECT pg_advisory_xact_lock(24071001);
ALTER TABLE product_types
 ADD COLUMN IF NOT EXISTS group_across_brands boolean NULL,
 ADD COLUMN IF NOT EXISTS class_label varchar(40) NULL;
CREATE TABLE IF NOT EXISTS catalog_family_cards (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_id bigint NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
 product_type_id bigint NOT NULL REFERENCES product_types(id) ON DELETE CASCADE,
 key varchar(200) NOT NULL,
 image_url varchar(2048) NULL,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 created_by_id bigint NULL, updated_by_id bigint NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_catalog_family_cards_category_id_product_type_id_key ON catalog_family_cards(category_id,product_type_id,key);
CREATE INDEX IF NOT EXISTS ix_catalog_family_cards_product_type_id ON catalog_family_cards(product_type_id);
COMMIT;

\echo 'Check (expect: catalog_family_cards 0; product_types unchanged, both new columns empty):'
SELECT count(*) AS catalog_family_cards FROM catalog_family_cards;
SELECT count(*) AS product_types, count(group_across_brands) AS group_settings, count(class_label) AS label_settings FROM product_types;
