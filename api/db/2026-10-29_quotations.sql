-- =====================================================================================================
-- BuildMate — Quotations (request a price → store quotes → customer accepts and pays)       2026-10-29
--
-- For databases created BEFORE this change (the API creates the schema with EnsureCreated, so new tables
-- are NOT added automatically). Fresh databases get these tables from the code; don't run it there.
--
-- RUN BY HAND, after a backup, on staging first:
--     pg_dump -Fc -d buildmate -f buildmate_before_quotations.dump
--     psql -d buildmate -v ON_ERROR_STOP=1 -f 2026-10-29_quotations.sql
--
-- What it changes
--   * Adds two NEW tables (quotations, quotation_items) and one sequence (quote_no_seq).
--   * Existing tables are not altered. orders / order_items / products are only referenced by foreign keys.
--   * Safe to re-run: IF NOT EXISTS everywhere.
--
-- Rollback (only while no quotation has been accepted — accepted ones point at real orders):
--     DROP TABLE quotation_items; DROP TABLE quotations; DROP SEQUENCE quote_no_seq;
-- =====================================================================================================

BEGIN;

CREATE SEQUENCE IF NOT EXISTS quote_no_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS quotations (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_no         character varying(30)    NOT NULL,
    user_id          bigint                   NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    customer_kind    integer                  NOT NULL,
    channel          integer                  NOT NULL,
    status           integer                  NOT NULL,
    fulfilment_type  integer                  NOT NULL,
    address_id       bigint                   NULL,
    preferred_at     timestamp with time zone NULL,
    customer_notes   character varying(1000)  NULL,
    customer_name    text                     NOT NULL,
    customer_phone   text                     NULL,
    sub_total        numeric(14,2)            NOT NULL,
    discount_total   numeric(14,2)            NOT NULL,
    shipping_fee     numeric(14,2)            NOT NULL,
    round_off        numeric(14,2)            NOT NULL,
    grand_total      numeric(14,2)            NOT NULL,
    store_message    character varying(1000)  NULL,
    quoted_at        timestamp with time zone NULL,
    quoted_by_id     bigint                   NULL,
    quoted_by_name   text                     NULL,
    valid_until      timestamp with time zone NULL,
    responded_at     timestamp with time zone NULL,
    cancel_reason    text                     NULL,
    order_id         bigint                   NULL REFERENCES orders (id) ON DELETE SET NULL,
    created_at       timestamp with time zone NOT NULL,
    updated_at       timestamp with time zone NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_quotations_quote_no              ON quotations (quote_no);
CREATE INDEX        IF NOT EXISTS ix_quotations_status_created_at     ON quotations (status, created_at);
CREATE INDEX        IF NOT EXISTS ix_quotations_user_id_created_at    ON quotations (user_id, created_at);
CREATE INDEX        IF NOT EXISTS ix_quotations_order_id              ON quotations (order_id);

CREATE TABLE IF NOT EXISTS quotation_items (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id              bigint        NOT NULL REFERENCES quotations (id) ON DELETE CASCADE,
    product_id                bigint        NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
    product_code              text          NOT NULL,
    product_name              text          NOT NULL,
    quantity                  numeric(14,3) NOT NULL,
    list_price                numeric(14,2) NOT NULL,
    discount_percent          numeric(6,2)  NOT NULL,
    special_discount_percent  numeric(6,2)  NOT NULL,
    unit_price                numeric(14,2) NOT NULL,
    line_total                numeric(14,2) NOT NULL,
    gst_rate                  numeric(6,2)  NOT NULL,
    reward_points             numeric(14,2) NOT NULL,
    created_at                timestamp with time zone NOT NULL,
    updated_at                timestamp with time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_quotation_items_quotation_id ON quotation_items (quotation_id);
CREATE INDEX IF NOT EXISTS ix_quotation_items_product_id   ON quotation_items (product_id);

COMMIT;

\echo 'Check (expect 0 rows each, and the sequence at 1):'
SELECT count(*) AS quotations FROM quotations;
SELECT count(*) AS quotation_items FROM quotation_items;
SELECT last_value FROM quote_no_seq;
