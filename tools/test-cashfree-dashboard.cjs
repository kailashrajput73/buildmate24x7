// UI-only browser test. Uses local admin login and intercepts every payment-settings request.
// No payment settings are written to the real backend; all credential values here are test fixtures.
const { chromium } = require('../.local-tools/browser/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')

;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const login = await page.request.post('http://127.0.0.1:5173/api/auth/staff/login', { data: { email: 'admin@buildmate24x7.in', password: process.env.BUILDMATE_LOCAL_ADMIN_PASSWORD || 'Admin@12345' } })
    assert.equal(login.status(), 200)
    const session = await login.json()
    await page.addInitScript(session => localStorage.setItem('bm_admin_session', JSON.stringify(session)), session)
    let status = { revision: 0, activated: false, mode: 'sandbox', effectiveMode: 'sandbox', sandboxConfigured: false, productionConfigured: false, legacyConfigured: false }
    const saves = []
    await page.route('**/api/admin/settings/cashfree**', async route => {
      if (route.request().url().endsWith('/audit')) return route.fulfill({ json: [] })
      if (route.request().method() === 'PUT') {
        const body = route.request().postDataJSON()
        saves.push(body)
        status = { ...status, revision: status.revision + 1, mode: body.mode, activated: body.activate || status.activated,
          sandboxConfigured: !!body.sandbox || status.sandboxConfigured, productionConfigured: !!body.production || status.productionConfigured }
        if (status.activated) status.effectiveMode = body.mode
      }
      await route.fulfill({ json: status })
    })
    await page.goto('http://127.0.0.1:5173/settings')
    const section = page.locator('#cashfree-payment-gateway')
    const testTab = section.getByRole('radio', { name: 'Test Mode', exact: true })
    const liveTab = section.getByRole('radio', { name: 'Live Mode', exact: true })
    const testForm = section.locator('#cashfree-sandbox-credentials')
    const liveForm = section.locator('#cashfree-production-credentials')
    await testTab.waitFor()
    assert.equal(await testTab.isChecked(), true)
    assert.equal(await testForm.isVisible(), true)
    assert.equal(await liveForm.isVisible(), false)
    await liveTab.check()
    assert.equal(await testTab.isChecked(), false)
    assert.equal(await liveForm.isVisible(), true)
    assert.equal(await testForm.isVisible(), false)
    await section.getByRole('checkbox').check()
    assert.equal(await section.getByRole('button', { name: 'Save Cashfree settings' }).isDisabled(), true)
    assert.equal(await section.getByText(/Live credentials are not configured/).isVisible(), true)
    assert.equal(saves.length, 0)
    await section.getByRole('checkbox').uncheck()
    await testTab.check()
    await section.getByLabel('Test Client ID', { exact: true }).fill('TEST-client-id-123')
    await section.getByLabel('Test Client Secret', { exact: true }).fill('TEST-secret-value-123456789')
    await liveTab.check()
    assert.equal(await testForm.isVisible(), false)
    await section.getByLabel('Live Client ID', { exact: true }).fill('LIVE-client-id-123')
    await section.getByLabel('Live Client Secret', { exact: true }).fill('LIVE-secret-value-123456789')
    await testTab.check()
    assert.equal(await section.getByLabel('Test Client ID', { exact: true }).inputValue(), 'TEST-client-id-123')
    assert.equal(await section.getByLabel('Test Client Secret', { exact: true }).inputValue(), 'TEST-secret-value-123456789')
    await liveTab.check()
    assert.equal(await section.getByLabel('Live Client ID', { exact: true }).inputValue(), 'LIVE-client-id-123')
    assert.equal(await section.getByLabel('Live Client Secret', { exact: true }).inputValue(), 'LIVE-secret-value-123456789')
    assert.equal(saves.length, 0, 'Switching forms must not save or activate anything')
    await testTab.check()
    await section.getByRole('button', { name: 'Save Cashfree settings' }).click()
    await page.waitForFunction(() => document.querySelector('#cashfree-payment-gateway input[type="password"]').value === '')
    assert.equal(saves.length, 1)
    assert.equal(saves[0].activate, false)
    assert.equal(saves[0].sandbox.clientId, 'TEST-client-id-123')
    assert.equal(saves[0].production.clientId, 'LIVE-client-id-123')
    assert.equal(await section.getByText('Test credentials: Configured', { exact: true }).isVisible(), true)
    assert.equal(await section.getByText('Live credentials: Configured', { exact: true }).isVisible(), true)
    await section.getByRole('radio', { name: 'Live Mode', exact: true }).check()
    await section.getByRole('checkbox').check()
    await section.getByRole('button', { name: 'Save Cashfree settings' }).click()
    await page.getByRole('dialog', { name: 'Switch to Live Mode?' }).waitFor()
    assert.equal(saves.length, 1, 'Live mode must not save before confirmation')
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.equal(saves.length, 1)
    await section.getByRole('button', { name: 'Save Cashfree settings' }).click()
    await page.getByRole('button', { name: 'Confirm Live Mode and save' }).click()
    await page.getByText('Currently effective: Live Mode (Production)', { exact: true }).waitFor()
    assert.equal(saves[1].confirmLive, true)
    assert.equal(saves[1].sandbox, undefined, 'Blank fields must preserve saved credentials')
    assert.equal(saves[1].production, undefined)
    await page.reload()
    await page.getByText('Currently effective: Live Mode (Production)', { exact: true }).waitFor()
    assert.equal(await testTab.isChecked(), true, 'Opening the page defaults to Test even when Live is active')
    assert.equal(await testForm.isVisible(), true)
    assert.equal(await liveForm.isVisible(), false)
    assert.equal(saves.length, 2, 'Reloading must not change the active Live configuration')
    assert.equal(status.effectiveMode, 'production')
    assert.equal(await section.getByLabel('Test Client Secret', { exact: true }).inputValue(), '')
    await liveTab.check()
    assert.equal(await section.getByLabel('Live Client Secret', { exact: true }).inputValue(), '')
    await testTab.check()
    await section.getByRole('button', { name: 'Save Cashfree settings' }).click()
    await page.getByText('Currently effective: Test Mode (Sandbox)', { exact: true }).waitFor()
    assert.equal(saves[2].mode, 'sandbox')
    assert.equal(saves[2].sandbox, undefined)
    assert.equal(saves[2].production, undefined)
    await page.reload()
    await page.getByText('Currently effective: Test Mode (Sandbox)', { exact: true }).waitFor()
    assert.equal(await testTab.isChecked(), true)
    assert.equal(await liveForm.isVisible(), false)
    assert.equal(saves.length, 3)
    assert.equal(await section.getByText('Test credentials: Configured', { exact: true }).isVisible(), true)
    assert.equal(await section.getByText('Live credentials: Configured', { exact: true }).isVisible(), true)
    assert.equal(await page.evaluate(() => JSON.stringify(localStorage).includes('secret-value')), false)
    await page.locator('[data-sonner-toast]').first().waitFor({ state: 'hidden' })
    fs.mkdirSync('.local-run/cashfree', { recursive: true })
    await section.screenshot({ path: '.local-run/cashfree/dashboard-desktop.png' })
    await page.setViewportSize({ width: 390, height: 844 })
    await section.screenshot({ path: '.local-run/cashfree/dashboard-mobile.png' })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'No horizontal overflow on mobile')
    console.log('PASS: single visible form, Test default with active Live preserved, both unsaved drafts retained, no PUT on tab changes/reload, missing Live activation blocked, save/confirmation/cancel, independent credentials after reload, no browser storage secrets, responsive layout')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
